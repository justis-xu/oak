"""中文同义词表（纯词法，零向量）：检索关键词无命中时的自动扩展。

来源：iter5-12 失败案例的词法失配归纳（奶奶/祖母、长跑/公益跑、身份/跨性别…）。
扩展只在直接命中为空时启用，并在观察里注明，不改变主体归因语义。
"""
from __future__ import annotations

# 词 → 同义/近义扩展（双向使用：查词命中为空时，把扩展词并入查询）
SYNONYMS: dict[str, list[str]] = {
    # 称谓
    "祖母": ["奶奶"], "奶奶": ["祖母"], "外婆": ["姥姥"],
    "先生": ["丈夫"], "丈夫": ["先生"], "老公": ["丈夫"],
    "女儿": ["闺女"], "闺女": ["女儿"], "儿子": ["孩子"],
    "母亲": ["妈妈"], "妈妈": ["母亲"], "父亲": ["爸爸"],
    # 活动与运动
    "长跑": ["公益跑", "马拉松", "跑步"], "马拉松": ["长跑", "公益跑"],
    "公益跑": ["长跑", "慈善"], "慈善跑": ["公益跑"],
    "读书": ["阅读", "看书", "读"], "阅读": ["读书", "看书"],
    "看书": ["读书", "阅读"],
    "徒步": ["爬山", "远足", "健行"], "远足": ["徒步"],
    "露营": "野营 露营".split(), "野营": ["露营"],
    "陶艺": ["陶罐", "黏土", "陶艺课"],
    "演唱会": ["音乐会", "演出", "现场"], "音乐会": ["演唱会", "演出"],
    "演出": ["演唱会", "音乐会", "表演"],
    # 抽象词 → 内容词（问句常用抽象词，事实用内容词）
    "身份": ["跨性别", "转变", "女性"],
    "领域": ["职业", "学业", "专业"],
    "职业": ["工作", "事业"],
    "感受": ["觉得", "感到", "开心", "感激"],
    "挫折": ["受伤", "困难", "失败", "事故"],
    "乐器": ["吉他", "钢琴", "小提琴", "单簧管"],
    "放松": ["减压", "平静", "解压"],
    "减压": ["放松", "压力"],
    "象征": ["代表", "意味着", "寓意"],
    "计划": ["打算", "想要", "准备"],
    # 常用译名漂移
    "书": ["著作", "读"], "著作": ["书"],
    "画": ["绘画", "画作", "作品"], "绘画": ["画", "画作"],
    "作品": ["画", "陶罐", "碗"],
}


def expand(keyword: str) -> list[str]:
    """词 → [自身] + 同义扩展（不含空值）。"""
    out = [keyword]
    for v in SYNONYMS.get(keyword, []):
        if v and v not in out:
            out.append(v)
    return out


def expand_all(keywords: list[str]) -> tuple[list[str], list[str]]:
    """关键词组 → (含扩展的完整组, 实际新增的扩展词)。"""
    full, added = list(keywords), []
    for k in keywords:
        for v in expand(k):
            if v not in full:
                full.append(v)
                added.append(v)
    return full, added
